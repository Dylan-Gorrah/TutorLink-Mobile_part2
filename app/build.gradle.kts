// Supabase URL + anon key come from local.properties (never committed).
// CI has no local.properties, so placeholders keep the build and tests working.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
